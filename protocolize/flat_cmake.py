"""One flat CMake build for ONE state of a mixed Fortran/C++ tree.

The flow converts a large Fortran project a few units at a time, flipping
each one between its Forthran and C++ forms and rebuilding to see whether
the result still agrees with a reference.  Doing that by editing build
files means editing them per corpus and per flip, which is how three
per-corpus builder modules came to exist — one idea implemented three times
with three sets of conventions hiding behind duck typing.

This expresses it once.  A protocol says what the build is (its units, its
link products, its module graph); a state table says which form each unit
takes; the two produce one ``CMakeLists.txt``.

**The link line follows the state.**  A product's members are recorded as
STEMS, so flipping a unit changes which object the link line names without
the product definition changing.  Recorded as ``isamax.f.o`` it would pin
one form: the converted unit's object would no longer be the one asked for,
and the build would die on an undefined reference to a symbol with no file
to point at.

**Intent, not commands.**  The protocol carries a full command per unit, so
this could emit one ``add_custom_command`` each and reproduce every command
character for character.  It deliberately does not.  Expressing the intent
— these sources, these flags, this product — and letting CMake assemble the
command keeps what CMake already does correctly:

* module and header dependencies, including the ``.mod`` ordering a Fortran
  build needs, which a dispatched build would have to reimplement;
* the two forms do not collide, because CMake names an object after its
  source (``isamax.f.o`` vs ``isamax.cpp.o``), so a flip neither deletes
  nor overwrites the other side's object and repeated trial builds stay
  cheap;
* it is what the corpora already do.

The cost is that a command is REASSEMBLED rather than copied, so it can
drift — which is what the protocol's own record of the command is for.
"""

from __future__ import annotations

import json
import shlex
import warnings
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

from protocolize.private_protocol import (CompileEntry, Protocol, ProtocolError,
                                  expand_tree)

#: The states that mean "this unit has been converted".
#:
#: ONE definition for the whole project.  A second spelling anywhere is a
#: second opinion about the same state table, and the two will disagree.
CONVERTED_STATES = ('PASS', 'WIP')

_HEADER = """\
# Generated by deepf2c — a flat build for ONE state.
# Do not edit: regenerate from the protocol + the state table.
# Do not commit: it is a temporary artifact of a mixed state.
"""


class ClosureWarning(UserWarning):
    """A state entry that the module graph cannot honour was demoted."""


@dataclass
class Reconciled:
    """A state table with its unreachable entries returned to Fortran."""

    state: dict[str, str] = field(default_factory=dict)
    #: The stems that were asked for a converted form and cannot take it.
    demoted: list[str] = field(default_factory=list)
    messages: list[str] = field(default_factory=list)


def reconcile_state(protocol: Protocol, state: dict[str, str],
                    *, default: str = 'fortran') -> Reconciled:
    """*state* with every unreachable conversion demoted, and why.

    A converted unit emits no Fortran ``.mod``, so a unit that a still-Fortran
    unit ``use`` s can only be converted once its Fortran CONSUMERS have
    gone.  That is the layering the loop depends on, and a state table is an
    input to it rather than a promise: an entry asking to convert a provider
    that is still needed is not an error to report, it is an entry to bring
    back to ``TODO`` so the build is one that can exist.

    Pure, so a caller can persist the answer: the loop reconciles BEFORE
    writing the state it will build from, and ``flat_cmake`` reconciles
    again from the same function — one rule, two uses, no second opinion.
    """
    out = dict(state)
    demoted: list[str] = []
    messages: list[str] = []
    # Iterate to a fixed point: demoting a provider can un-convert a unit
    # whose OWN module another still-Fortran unit needed in turn.  One pass
    # would leave the second layer stranded, which is the same defect one
    # step later.
    by_stem = protocol.variants()
    # The offenders are computed from the GRAPH, not by reading the
    # violations' text back: a message names the CONSUMER first, so a scan
    # keyed on the message finds the wrong side — and parsing prose to
    # recover a fact this function already has is how the next rewrite of
    # that sentence becomes a silent bug.
    provider: dict[str, str] = {}
    for stem, forms in by_stem.items():
        for entry in forms.values():
            for mod in entry.provides:
                provider.setdefault(mod.lower(), stem)
    for _ in range(len(by_stem) + 1):     # bounded: a fixed point is reached
        from_state = _state_for_stems(out, by_stem)
        converted = {s for s in by_stem
                     if from_state.get(s) in CONVERTED_STATES}
        offenders: list[str] = []
        for stem, forms in by_stem.items():
            if stem in converted:
                continue               # it stays Fortran; it is the victim
            for entry in forms.values():
                for mod in entry.uses:
                    owner = provider.get(mod.lower())
                    if owner is not None and owner in converted:
                        offenders.append(owner)
        if not offenders:
            break
        for stem in offenders:
            out[stem] = default if default != 'fortran' else 'TODO'
            demoted.append(stem)
        messages.append(
            f'{len(set(offenders))} unit(s) demoted to TODO: a module they '
            f'provide is still used by Fortran units that are not converted '
            f'in this state ({", ".join(sorted(set(offenders))[:3])}'
            + (', ...' if len(set(offenders)) > 3 else '') + ')')
    return Reconciled(state=out, demoted=sorted(set(demoted)),
                      messages=messages)


@dataclass
class Selection:
    """What each stem resolved to, plus anything that could not resolve."""

    entries: dict[str, CompileEntry] = field(default_factory=dict)
    missing: list[str] = field(default_factory=list)


def object_name_for(stem: str, variant: str) -> str:
    """The object one form of *stem* builds, as a CMake target knows it.

    The two forms must NOT share a name: a shared one makes a flip rebuild
    the unit every time and, worse, lets a stale object from the other form
    answer for the current one.
    """
    suffix = '.cpp.o' if variant == 'cpp' else '.f.o'
    return f'{stem}{suffix}'


def select(protocol: Protocol, state: dict[str, str],
           *, default: str = 'fortran') -> Selection:
    """Each stem's form, from the state table.

    The state table is keyed by a source path WITH its extension
    (``mds/defcor.f``); the protocol is keyed by the extension-independent
    stem (``mds/defcor``).  The comparison therefore drops the extension —
    and matches on the tail, because the two are measured from different
    roots.

    A stem the state NAMES and for which the wanted form does not exist is
    REPORTED, not silently built as the other: that would be a build that
    does not match the state, and it is exactly the shape a protocol with
    one form per stem takes — measured, 6794 diagnostics on the real corpus.

    A stem the state does NOT name is a different matter.  A corpus ships
    units in one language (MYSTRAN's 243 C files, whose Fortran form does
    not exist and whose conversion is meaningless), and a state table, which
    names the stems TO CONVERT, says nothing about them.  A stem with one
    form and no instruction therefore keeps that form — silence is not a
    request to convert.  Reporting those was 243 diagnostics that fire on a
    healthy corpus, which is how a diagnostic stops being read.
    """
    by_stem = protocol.variants()
    from_state = _state_for_stems(state, by_stem)

    chosen: dict[str, CompileEntry] = {}
    missing: list[str] = []
    for stem, forms in by_stem.items():
        named = stem in from_state
        want = 'cpp' if from_state.get(stem) in CONVERTED_STATES else default
        entry = forms.get(want)
        if entry is None:
            if not named and len(forms) == 1:
                # The state says nothing about this stem and only one form
                # exists, so that form is not a fallback -- it is the answer.
                chosen[stem] = next(iter(forms.values()))
                continue
            other = 'fortran' if want == 'cpp' else 'cpp'
            alt = forms.get(other)
            if alt is None:
                raise ProtocolError(f'{stem} has no entry in either form')
            missing.append(
                f'{stem}: the state wants {want} and the protocol has only '
                f'{other}')
            chosen[stem] = alt
            continue
        chosen[stem] = entry
    return Selection(entries=chosen, missing=missing)


def _tail_key(text: str) -> str:
    """The comparison form of a stem or a state key: basename, no extension.

    The two spellings are measured from different roots (the state table
    from the corpus root, the stem from wherever the protocol was captured),
    so the whole path cannot be compared.  The basename is what both are
    guaranteed to share.
    """
    from protocolize.private_protocol import canonical_stem
    return canonical_stem(text).rsplit('/', 1)[-1].lower()


def _state_for_stems(state: dict[str, str], by_stem: dict) -> dict[str, str]:
    """*state*, keyed the way :func:`select` will look it up.

    A state key is the TAIL of a stem, and it may denote SEVERAL stems:
    LAPACK's ``xerbla_64`` exists in twenty products, and ``lsame`` /
    ``lsame_64`` exist in both BLAS and LAPACK.  Indexing ``{tail: stem}``
    keeps whichever came last and drops the rest, which leaves those stems
    on the Fortran default — measured: 238 of LAPACK's stems.  So the index
    maps a tail to EVERY stem it denotes.
    """
    if not state:
        return {}
    by_tail: dict[str, list[str]] = {}
    for stem in by_stem:
        by_tail.setdefault(_tail_key(stem), []).append(stem)
    out: dict[str, str] = {}
    for key, value in state.items():
        for stem in by_tail.get(_tail_key(key), ()):
            out[stem] = value
    return out


def closure_violations(protocol: Protocol, state: dict[str, str]) -> list[str]:
    """States in which a Fortran unit's module is provided by a converted one.

    A converted unit emits no Fortran ``.mod``, so if a unit still compiles
    as Fortran and ``use`` s a module, whoever provides it must still be
    compiling as Fortran — otherwise the unit cannot build at all.  That is
    what lets the module graph be handed to the build system instead of
    reimplemented: under closure every ``.mod`` a remaining Fortran source
    needs is produced by another remaining Fortran source.
    """
    by_stem = protocol.variants()
    from_state = _state_for_stems(state, by_stem)

    provider: dict[str, str] = {}
    for e in protocol.compilation:
        for mod in e.provides:
            provider.setdefault(mod.lower(), e.stem)

    converted = {s for s in by_stem if from_state.get(s) in CONVERTED_STATES}
    out: list[str] = []
    for stem in by_stem:
        if stem in converted:
            continue
        for e in by_stem[stem].values():
            for mod in e.uses:
                owner = provider.get(mod.lower())
                if owner is not None and owner in converted:
                    out.append(
                        f'{stem} (Fortran) uses module {mod!r}, provided by '
                        f'{owner}, which is converted to C++')
    return out


def flat_cmake(protocol: Protocol, state: dict[str, str] | None = None, *,
               tree: str | Path, runtime_include: str,
               name: str = 'CMakeLists.txt') -> str:
    """Write the flat CMakeLists for *state*; return its path.

    **Self-contained on purpose.**  This module knows nothing about the flow,
    the state table's file format, or any corpus: it takes a protocol and a
    mapping, and produces a build.  That is what lets the same call serve
    both a flip loop (protocol + live state) and a proof (a Fortran-only
    protocol and no state at all) without either learning about the other.

    *state* is OPTIONAL and its absence is meaningful: no state means every
    unit stays in the form its protocol entry already records, so a protocol
    captured from a pure-Fortran build replays as pure Fortran.  A caller
    proving a freshly extracted protocol has no state to offer, and having to
    pass an empty dict to say "nothing is converted" would make the simplest
    use the one that looks like a special case.

    *state* maps a source key to a status; anything not in
    :data:`CONVERTED_STATES` takes the Fortran form.

    *runtime_include* is the directory CONTAINING ``runtime/`` — the deepf2c
    source root.  It is an argument rather than derived, because nothing at
    this level knows where the checkout is: a path guessed from the
    generated file's own location is right only by coincidence, and wrong in
    a way that surfaces as a missing header deep in a build.
    """
    tree_s = str(tree)
    # THE LAYERING, applied where the two inputs meet.  `closure_violations`
    # has described this rule since this module was written and was never
    # called: a state that converts a unit whose module a still-Fortran unit
    # `use`s produces a build that looks fine and dies in the COMPILE step,
    # naming a `.mod` in a file three steps from the cause.
    #
    # The state table is an INPUT, so an unreachable entry is reconciled
    # rather than refused: the provider goes back to Fortran and the caller
    # is told which and why.  Refusing instead would make the loop's only
    # recourse to re-derive what this function already knows, and a loop
    # that re-derives a rule will eventually derive it differently.
    reconciled = reconcile_state(protocol, state or {})
    for message in reconciled.messages:
        warnings.warn(message, ClosureWarning, stacklevel=2)
    chosen = select(protocol, reconciled.state)
    if chosen.missing:
        # LOUD, because the alternative is a build that does not match the
        # state while looking like it does.  Measured: an all-PASS state
        # table over a protocol with one form per stem produced 6794
        # diagnostics that nobody read and a pure-Fortran build.  A caller
        # that cannot be honoured has to hear about it here, where the two
        # inputs are still in hand.
        worst = chosen.missing[:5]
        more = len(chosen.missing) - len(worst)
        raise ProtocolError(
            f'{len(chosen.missing)} stem(s) cannot take the form the state '
            f'asks for:\n  ' + '\n  '.join(worst)
            + (f'\n  ... and {more} more' if more > 0 else '')
            + '\nThe state names a form the protocol does not carry; supply '
              'the derived C++ protocol alongside the Fortran one.')
    text = _render(protocol, chosen, tree_s, str(runtime_include))
    out = Path(tree) / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    return str(out)


def _render(protocol: Protocol, selection: Selection, tree: str,
            runtime_include: str) -> str:
    lines: list[str] = [_HEADER, '']
    if not _has_fortran(selection):
        lines.append('project(f2c_state LANGUAGES C CXX)')
    else:
        lines.append('project(f2c_state LANGUAGES C CXX Fortran)')
    lines.append('set(CMAKE_POSITION_INDEPENDENT_CODE ON)')
    if _has_fortran(selection):
        # The MODULE DIRECTORY is the build system's to manage, and it has to
        # be, because a `.mod` is a compile-time dependency and nothing in a
        # flat list of sources says so.  CMake scans a Fortran source for its
        # `use` statements, writes every module into this one directory, and
        # derives the compile ORDER from that — which is the whole reason the
        # flags a unit was compiled with are not replayed verbatim (see the
        # flag table's `module_dir`).
        #
        # BEFORE the first target, because that is when CMake READS it: the
        # variable is consulted as each target is created, so a `set()`
        # emitted after them is dead code that looks like a declaration.
        # Measured: set at line 16850 with the first target at 13479, so all
        # 1306 `.mod` files landed in the build root instead of here — and
        # the build still succeeded, which is why nobody noticed.
        lines.append(
            f'set(CMAKE_Fortran_MODULE_DIRECTORY "{tree}/bin/mod")')
        if not _build_preprocesses(selection):
            # The SCAN is a C preprocessor, and it is not free.  CMake runs
            # one over every Fortran source to find its `use` statements, so
            # a fixed-form source whose COMMENT contains `/*` dies:
            #
            #   C   ... REPLACEING !* BY /* IN RDMAP ARRAY
            #   Error: unterminated comment
            #
            # Measured on NASTRAN-95, whose build compiles all 1830 units in
            # ONE step (`gfortran -c -o x.o x.f`, no `-cpp`): the added scan
            # turned a valid corpus into a build that fails on a comment.
            # A replay declares what the corpus does, no more.
            #
            # OFF and not "unset": unset is the default, and the default is
            # ON.  Before the first target, for the same reason the module
            # directory is — CMake reads it as each target is created.
            lines.append('set(CMAKE_Fortran_PREPROCESS OFF)')
    lines.append('')

    # ── the units ──
    # The chosen form of each stem, with the flags its own command carried.
    per_form: dict[str, list[str]] = {}
    for stem in sorted(selection.entries):
        e = selection.entries[stem]
        form = e.variant or 'fortran'
        per_form.setdefault(form, []).append(stem)

    # ── the sources the build must MAKE first ──
    # A corpus that generates sources compiles files it does not ship --
    # LAPACK's 3,489 `_64` mirrors, MYSTRAN's 570.  Each is recorded with
    # the command that produces it; emitting that command back is what makes
    # a replay possible at all, and leaving it out is a build that dies on
    # one missing file among thousands.
    generated = _generated_rules(protocol, tree)
    if generated:
        lines.append('# Sources this build must generate before compiling.')
        for out, command, depends in generated:
            lines.append(f'add_custom_command(OUTPUT "{_cmake_string(out)}"')
            # Every rule runs in a shell, because the recorded command IS a
            # shell line: a build system runs its commands through one, and
            # the recorded text contains `cd X && ...` and its own quoting.
            # Handing it to CMake as an argument list would split it wrongly.
            # The parent directory is made first: in a FRESH tree the
            # directory a generated source lands in does not exist, and the
            # generator is not obliged to create it.
            parent = str(Path(out).parent)
            lines.append(f'  COMMAND "${{CMAKE_COMMAND}}" -E make_directory '
                         f'"{_cmake_string(parent)}"')
            lines.append(f'  COMMAND sh -c "{_shell_arg(command)}"')
            for dep in depends:
                lines.append(f'  DEPENDS "{_cmake_string(dep)}"')
            lines.append('  VERBATIM)')
        lines.append('')

    for stem in sorted(selection.entries):
        e = selection.entries[stem]
        lines.append(f'# {stem}')
        lines.append(f'set(_src_{_ident(stem)} '
                     f'"{_cmake_string(_expand(e.file, tree))}")')

    for stem, e in sorted(selection.entries.items()):
        flags = flags_from_command(e.command_line(), e.file)
        if flags:
            # Each flag expanded, then joined as a CMake LIST.  Joined with
            # spaces inside one quoted argument they reach the compiler as a
            # single option -- an include path becomes the argument
            # "-I/tree/src -fpreprocessed", which names no directory, draws
            # only a warning, and leaves a build that looks successful.
            lines.append(
                f'set_source_files_properties("${{_src_{_ident(stem)}}}" '
                f'PROPERTIES COMPILE_OPTIONS '
                f'"{_cmake_list(_expand(f, tree) for f in flags)}")')
    lines.append('')

    # ── the products ──
    # Members are stems, so this is the same definition in every state; the
    # objects it resolves to are what change.
    #
    # Where they LAND is this generator's decision, not the project's.  The
    # protocol records where the project's own build put its artifacts, and
    # that is a fact about a build system this one does not use — MYSTRAN's
    # executable is in `src_overlay/Binaries/`, a Makefile project's is in
    # the directory it was linked in.  Reproducing those shapes would spread
    # one generator's output across every convention its inputs happen to
    # have, and leave whoever consumes the build with no fixed place to
    # look.  One directory, named once.
    bin_dir = f'{tree}/bin'.replace('\\', '/')
    orphans = _unlinked_units(protocol, selection)
    # Every module USED anywhere in this build.  A provider whose module is
    # on this list has a consumer to be ordered against; one that is not has
    # none, and only the first target needs to compile it.
    ever_used = {m.lower() for e in selection.entries.values()
                 for m in e.uses}
    for i, prod in enumerate(protocol.products):
        out = _cmake_string(expand_tree(prod.output, tree))
        if prod.kind == 'archive':
            lines.append(f'add_library(_prod_{i} STATIC)')
            for stem in prod.members:
                if stem not in selection.entries:
                    continue
                lines.append(
                    f'target_sources(_prod_{i} PRIVATE '
                    f'"${{_src_{_ident(stem)}}}")')
            for stem in _orphans_needed_by(orphans, prod.members,
                                           selection, ever_used,
                                           first=(i == _first_product(
                                               protocol))):
                lines.append(
                    f'target_sources(_prod_{i} PRIVATE '
                    f'"${{_src_{_ident(stem)}}}")')
            lines.append(f'set_target_properties(_prod_{i} PROPERTIES '
                         f'OUTPUT_NAME "{Path(out).stem[3:] if Path(out).stem.startswith("lib") else Path(out).stem}" '
                         f'ARCHIVE_OUTPUT_DIRECTORY "{bin_dir}")')
        elif prod.kind == 'exe':
            lines.append(f'add_executable(_prod_{i})')
            for stem in prod.objects:
                if stem not in selection.entries:
                    continue
                lines.append(
                    f'target_sources(_prod_{i} PRIVATE '
                    f'"${{_src_{_ident(stem)}}}")')
            for stem in _orphans_needed_by(orphans, prod.objects,
                                           selection, ever_used,
                                           first=(i == _first_product(
                                               protocol))):
                lines.append(
                    f'target_sources(_prod_{i} PRIVATE '
                    f'"${{_src_{_ident(stem)}}}")')
            for lib in prod.libs:
                # A library this generator ALSO builds is linked by NAME, so
                # the link line follows the archive's own chosen location;
                # spelling its path here would pin it to where the PROJECT's
                # build put it, and the replay would look for an archive in
                # a directory it never writes to.
                lines.append(
                    f'target_link_libraries(_prod_{i} PRIVATE '
                    f'"{_lib_ref(lib, protocol, selection, tree)}")')
            blas_so = _blas_so(runtime_include)
            if blas_so is not None:
                # LAST on the line, and that ordering is load-bearing rather
                # than tidy.  The vendored OpenBLAS exports `dgemm_` as well
                # as `cblas_dgemm`, and a corpus that ships its own BLAS
                # links it as an archive of INDIVIDUAL units, not one object
                # file — so the linker only pulls the members an undefined
                # symbol still asks for.  Measured on a two-library link
                # with the corpus archive first: the corpus's `dgemm_` won;
                # with OpenBLAS first, OpenBLAS won and the substitution was
                # SILENT (no diagnostic, no duplicate-symbol error).  The
                # corpus's own BLAS must therefore be resolved before
                # OpenBLAS is consulted.
                lines.append(
                    f'target_link_libraries(_prod_{i} PRIVATE '
                    f'"{_cmake_string(str(blas_so))}" '
                    f'"-Wl,-rpath,{_cmake_string(str(blas_so.parent))}")')
            lines.append(f'set_target_properties(_prod_{i} PROPERTIES '
                         f'OUTPUT_NAME "{Path(out).name}" '
                         f'RUNTIME_OUTPUT_DIRECTORY "{bin_dir}")')
        else:
            raise ProtocolError(f'products[{i}]: unknown kind {prod.kind!r}')
    lines.append('')

    # ── how a converted unit is compiled ──
    lines.append('# The generated C++ includes the runtime by name, so its')
    lines.append('# parent directory has to be on the include path.')
    lines.append(f'include_directories("{_cmake_string(runtime_include)}")')

    # ── the corpus's own TEST registrations ──
    # A build that can be generated must also be RUNNABLE the way the project
    # runs it, and for a self-verifying corpus the suite IS the verdict: its
    # drivers check their own residuals and the aggregate table decides.  A
    # generated build with no registrations therefore cannot be verified at
    # all — measured, the tree built 7045/7045 objects and the benchmark died
    # in 0.022s with "no CTest registration".
    #
    # Nothing here is invented: the entries are the protocol's, captured
    # through the build system's own `ctest --show-only=json-v1`, re-spelled
    # against THIS tree so a replay registers its own artifacts rather than
    # the ones the protocol was captured from.
    # Files the tests READ that the build neither compiles nor generates.
    # Written as text, because there is no command to replay: LAPACK's
    # `*_64.in` are derived by a `string(REPLACE)` in the project's own
    # CMakeLists, and `lapack_testing.py` is `file(COPY)`d in.  CMake writes
    # them the same way, at configure time.
    support = list(getattr(protocol, 'support_files', ()) or ())
    for f in support:
        rel = _cmake_string(str(f.get('path') or ''))
        content = f.get('content')
        if not rel or content is None:
            continue
        # Written where CMake's own `file(COPY)` would have put it: the
        # BINARY directory.  The tests reference these by paths spelled
        # `CMAKE_CURRENT_BINARY_DIR` (see the re-rooting above), so writing
        # them to the source tree puts them one level away from every reader
        # — and the failure is a test that cannot find its input file.
        out_path = '${CMAKE_CURRENT_BINARY_DIR}/' + rel.replace('\\', '/')
        # A CMake BRACKET argument, because the content is source code: quotes,
        # semicolons and backslashes all survive it with no escaping at all.
        # The delimiter carries as many `=` as it takes for its own closing
        # sequence to be absent from the content — a fixed `[[...]]` breaks on
        # any file containing `]]`, and the failure is a PARSE error naming
        # the bracket rather than the file.
        eq = ''
        while f']{eq}]' in content:
            eq += '='
        # `file(WRITE)` does not create directories, and a registration
        # whose working directory does not exist is "Failed to change
        # working directory" rather than a missing file — the error names
        # the directory and not what would have been in it.
        parent = str(Path(out_path.replace('${CMAKE_CURRENT_BINARY_DIR}',
                                           '.'))).replace('\\', '/')
        parent = parent.rsplit('/', 1)[0]
        if parent and parent != '.':
            lines.append('')
            lines.append(f'file(MAKE_DIRECTORY '
                         f'"${{CMAKE_CURRENT_BINARY_DIR}}/{parent[2:]}")')
        lines.append('')
        lines.append(f'file(WRITE "{_cmake_string(out_path)}" '
                     f'[{eq}[{content}]{eq}])')

    tests = list(getattr(protocol, 'tests', ()) or ())
    if tests:
        lines.append('')
        lines.append('# The corpus\'s own test registrations, from the protocol.')
        lines.append('enable_testing()')
        # `${TREE}` means two different things to a test command, and the
        # difference only shows when the build is out-of-source:
        #
        #   * a path under `<tree>/bin` names a product THIS generator makes,
        #     and it lands where the generator puts it;
        #   * every other path was written relative to the CAPTURE build's
        #     BINARY directory (the project's CMakeLists spells them with
        #     `CMAKE_CURRENT_BINARY_DIR`), which is `<tree>` only when the
        #     build is configured in place.
        #
        # The reference trees are in-source, which is why `${TREE}` alone
        # looked right — and why the generated tree failed with
        # `Failed to change working directory to <tree>/TESTING` when its
        # registrations pointed at `<tree>/build/TESTING`.  Spelling the
        # second kind as `${CMAKE_CURRENT_BINARY_DIR}` makes them follow the
        # configure directory, which is what they meant all along.
        bin_prefix = f'{str(tree).replace(chr(92), "/")}/bin/'

        tree_prefix = str(tree).replace('\\', '/') + '/'

        def _rebase(path: str) -> str:
            """*path*, re-rooted to the configure directory when it is ours."""
            norm = path.replace('\\', '/').rstrip('/')
            if norm.startswith(bin_prefix):
                return path               # this generator's own product
            if norm == str(tree).replace('\\', '/').rstrip('/'):
                # The tree root ITSELF — LAPACK's summary test runs there.
                # A prefix test with a trailing separator misses it, and the
                # miss is silent: the registration keeps an absolute path to
                # the SOURCE tree, where the results are not.
                return '${CMAKE_CURRENT_BINARY_DIR}'
            if norm.startswith(tree_prefix):
                return '${CMAKE_CURRENT_BINARY_DIR}/' + norm[len(tree_prefix):]
            return path

        def _test_path(text: str) -> str:
            # The tree placeholder can sit INSIDE an argument rather than at
            # its start: `-DOUTPUT=${TREE}/TESTING/dec.out`.  Testing the
            # whole token against a prefix therefore matches the bare paths
            # and misses every `-D`, which is most of them — measured, 0 of
            # 196 re-rooted.
            spelled = expand_tree(_cmake_string(str(text)), tree)
            head, sep, value = spelled.partition('=')
            if sep and value.startswith('/'):
                return head + '=' + _rebase(value)
            return _rebase(spelled)

        # A registration whose WORKING_DIRECTORY does not exist fails with
        # "Failed to change working directory" — which names the directory
        # and not the test, so it is worth creating them all up front.  The
        # project's own CMakeLists gets them as a side effect of building
        # there; a generated build has to say so.
        # Every directory a test WRITES into, as well as the one it runs in.
        # The suite's aggregator (`lapack_testing.py`) discovers its inputs by
        # walking `<TESTING>/EIG`, `/LIN`, `/MATGEN`, so a directory that the
        # drivers would have created by writing into it has to exist before
        # the aggregator looks — otherwise it reports "testing directory
        # TESTING not found" and the whole run reads as a failure while 214 of
        # 215 tests passed.
        out_dirs: set[str] = set()
        for t in tests:
            for arg in (t.get('command') or ()):
                head, sep, value = _test_path(str(arg)).partition('=')
                if sep and head.startswith('-DOUTPUT') and value:
                    out_dirs.add(str(Path(value).parent))
        wd_dirs = {
            _test_path(str(t.get('working_directory')))
            for t in tests if t.get('working_directory')} | out_dirs
        for wd in sorted(wd_dirs):
            if wd.startswith('${CMAKE_CURRENT_BINARY_DIR}'):
                lines.append(f'file(MAKE_DIRECTORY "{_cmake_string(wd)}")')
        for t in tests:
            name = _cmake_string(str(t.get('name') or ''))
            command = [_test_path(c) for c in (t.get('command') or ())]
            if not name or not command:
                continue
            lines.append(f'add_test(NAME "{name}" COMMAND '
                         + ' '.join(f'"{c}"' for c in command) + ')')
            props: list[str] = []
            wd = t.get('working_directory')
            if wd:
                props.append(
                    f'WORKING_DIRECTORY "{_test_path(wd)}"')
            deps = t.get('depends') or []
            if deps:
                joined = ';'.join(str(d) for d in deps)
                props.append(f'DEPENDS "{joined}"')
            if props:
                lines.append(f'set_tests_properties("{name}" PROPERTIES '
                             + ' '.join(props) + ')')
    return '\n'.join(lines) + '\n'


def _first_product(protocol: Protocol) -> int:
    """The index of the first linkable product, or -1.

    The target that additionally compiles the unlinked units NOTHING uses.
    One is enough — they have no consumers to be ordered against — and one
    is required, because a unit no target builds is a unit that does not
    exist as far as the build is concerned.
    """
    for i, prod in enumerate(protocol.products):
        if prod.kind in ('archive', 'exe'):
            return i
    return -1


def _unlinked_units(protocol: Protocol,
                    selection: Selection) -> dict[str, frozenset[str]]:
    """``{stem: modules it provides}`` for every unit no product links.

    A unit can exist without linking into anything — LAPACK's `la_constants`
    provides a module and nothing else, and its object has no global symbols
    at all.  `products` says what LINKS; it does not say what exists, so a
    unit missing from every product is not thereby absent from the build.

    Measured: emitting only a product's members dropped `la_constants`, and
    the replay died in a CONSUMER — `Fatal Error: Cannot open module file
    'la_constants.mod'` — naming a `.mod` three steps from the cause.
    """
    linked: set[str] = set()
    for prod in protocol.products:
        linked.update(prod.members)
        linked.update(prod.objects)
    out: dict[str, frozenset[str]] = {}
    for stem, entry in selection.entries.items():
        if stem in linked:
            continue
        modules = frozenset(m.lower() for e in protocol.compilation
                            if e.stem == stem for m in e.provides)
        out[stem] = modules
    return out


def _orphans_needed_by(orphans: dict[str, frozenset[str]],
                       members: Iterable[str],
                       selection: Selection, ever_used: set[str],
                       *, first: bool = False) -> list[str]:
    """The unlinked units whose MODULE this target's own units use.

    Into the TARGET, not merely into the build: CMake derives Fortran
    compile order WITHIN a target, so a `.mod` produced in another target
    has no ordering edge to the compile that reads it — the same failure by
    a different route.

    *first* is for the first product, which additionally takes the unlinked
    units nothing uses at all: they still have to be compiled somewhere, and
    the alternative is a unit no target builds.
    """
    if not orphans:
        return []
    used: set[str] = set()
    for stem in members:
        entry = selection.entries.get(stem)
        if entry is not None:
            used.update(m.lower() for m in entry.uses)
    out = [stem for stem, modules in sorted(orphans.items())
           if modules & used]
    if first:
        # ... and the ones with NO consumer anywhere.  A unit nothing uses
        # still exists; leaving it out of every target is a unit the build
        # never compiles, which is the whole defect by another route.  One
        # target is enough, because with no consumer there is no order to
        # keep.
        taken = set(out)
        out += [stem for stem in sorted(orphans)
                if stem not in taken and not (orphans[stem] & ever_used)]
    return out


def _lib_ref(lib: str, protocol: Protocol, selection: Selection,
            tree: str) -> str:
    """How a link line should name *lib*.

    A library THIS build produces is named by its target, because the target
    is what knows where the archive ends up.  A library it does not produce
    — a system library, or one the project ships — keeps its path, because
    there is nothing here that would make it.
    """
    want = _resolve(expand_tree(lib, tree), tree)
    for i, prod in enumerate(protocol.products):
        if prod.kind != 'archive':
            continue
        # Compared RESOLVED, not as text: a link line may spell the archive
        # relatively (a Makefile does) while the product records it against
        # `${TREE}`, and a string compare then misses a library this build
        # really does produce.
        if _resolve(expand_tree(prod.output, tree), tree) != want:
            continue
        if prod.members and all(m in selection.entries for m in prod.members):
            return f'_prod_{i}'
    return _cmake_string(lib)


def _blas_so(runtime_include: str | Path) -> Path | None:
    """The vendored BLAS to put on a corpus executable's link line, or None.

    `f2c::matmul` dispatches REAL*4/REAL*8/COMPLEX*8/COMPLEX*16 to the CBLAS
    entry points (`src/runtime/array_intrinsics_v2.h`), so a converted unit
    that calls MATMUL has an undefined `cblas_dgemm` and a corpus's own
    Fortran BLAS cannot satisfy it — that exports `dgemm_`, not the C
    interface.  Without this the link fails.

    Derived from *runtime_include*, which every caller already supplies and
    which is by definition `<checkout>/src`: the BLAS sits beside it at
    `<checkout>/3rd/openblas/lib/`.  A second parameter would have to be
    threaded through the corpus layout and the self-check to say the same
    thing, and the two could then disagree.

    None when the file is absent, so a checkout without the vendored library
    still configures.  That is not a silent degradation: `F2C_NO_BLAS` is
    *not* defined here, so the call is still emitted and the link fails
    naming `cblas_dgemm`.
    """
    so = Path(runtime_include).parent / '3rd' / 'openblas' / 'lib' / 'libopenblas.so'
    return so if so.is_file() else None


def _resolve(path: str, tree: str) -> str:
    """*path* as an absolute path, relative spellings taken against *tree*."""
    p = Path(path)
    return str(p if p.is_absolute() else Path(tree) / p)


def _build_preprocesses(selection: Selection) -> bool:
    """Did the corpus's own build preprocess its Fortran sources?

    Asked of the entries, which RECORD it: a unit that went through a
    preprocess edge carries one, and a build with no such edge did not
    preprocess. The distinction is load-bearing in both directions — a
    corpus that preprocessed needs the scan (its `-D` set lives on that edge,
    and a converted unit has no Fortran scan in front of it), and one that did
    not must not acquire one.
    """
    return any(e.preprocess for e in selection.entries.values())


def _has_fortran(selection: Selection) -> bool:
    return any((e.variant or 'fortran') == 'fortran'
               for e in selection.entries.values())


def _ident(stem: str) -> str:
    return ''.join(c if c.isalnum() else '_' for c in stem)


def _expand(text: str, tree: str) -> str:
    """Expand the placeholder, refusing a result CMake would misread.

    ``${TREE}`` left in the text is NOT harmless: CMake spells its own
    variables ``${...}``, so a leftover placeholder is read as an empty
    CMake variable and every path silently loses its root.
    """
    out = expand_tree(text, tree)
    if '${' in out:
        raise ProtocolError(
            f'{text!r} still holds a "${{...}}" after expansion, which CMake '
            f'reads as one of its own (empty) variables')
    return out


def _cmake_string(text: str) -> str:
    return text.replace('\\', '/')


def _generated_rules(protocol: Protocol, tree: str) -> list[tuple]:
    """``(output, command, depends)`` for each generated source, expanded.

    Deduped by output: a build system may declare one generated file twice
    (once relative to the tree, once absolutely), and two rules producing
    one file is a build that either races or refuses.
    """
    seen: dict[str, tuple] = {}
    for g in protocol.generated_inputs:
        out = _expand(g['output'], tree)
        if out in seen:
            continue
        depends = [_expand(d, tree) for d in (g.get('depends') or ())]
        seen[out] = (out, _expand(g['command'], tree), depends)
    return [seen[k] for k in sorted(seen)]


def _shell_arg(command: str) -> str:
    r"""*command* escaped to sit inside a CMake double-quoted argument.

    Only a backslash and a double quote need escaping for CMake's own
    else -- including the quotes the recorded command carries around its own
    arguments -- must reach the shell as written, because it is the shell
    that has to read them.
    """
    return command.replace('\\', '\\\\').replace('"', '\\"')


def _cmake_list(items: 'Iterable[str]') -> str:
    """*items* as one CMake list value.

    ``;`` separates a list, and the flags themselves are passed through
    ESCAPED rather than re-quoted: a definition like
    ``-DF2C_ABI_GFORTRAN=""`` already carries quotes the compiler must see,
    and wrapping it again hands over different text than the build recorded.
    """
    out = []
    for item in items:
        out.append(_cmake_string(item)
                   .replace('\\', '\\\\').replace(';', '\\;')
                   .replace('"', '\\"'))
    return ';'.join(out)


#: The compiler option grammar, as data.  See the file's own `comment`.
#:
#: A driver's option grammar is fixed and documented, so it is enumerable —
#: and enumerable is exactly why it belongs in a table rather than in an
#: if-chain.  Hard-coded here, it would be one compiler's grammar wearing a
#: general name, and every other compiler would be silently mis-parsed:
#: arity is the thing that must be right, and getting it wrong is quiet (a
#: flag that takes an operand and is counted as taking none leaves the
#: operand behind as another input file).
_FLAG_TABLE: dict | None = None


def _flag_table() -> dict:
    """The driver option grammar, loaded once."""
    global _FLAG_TABLE
    if _FLAG_TABLE is None:
        path = Path(__file__).resolve().parent / 'data' / 'compiler_flags.json'
        _FLAG_TABLE = json.loads(path.read_text(encoding='utf-8'))
    return _FLAG_TABLE


def _driver_family(driver: str) -> str:
    """Which option grammar *driver* speaks, by its own basename."""
    name = Path(driver).name
    for family, prefixes in _flag_table()['drivers'].items():
        if family == 'comment':
            continue
        if any(name.startswith(p) for p in prefixes):
            return family
    return 'gfortran'          # the driver this project is built around


def _flags_of(driver: str) -> dict:
    """The four sets :func:`flags_from_command` classifies with.

    Copied out of the table and closed over the driver, so the loop below
    asks set membership rather than re-deriving the family per token.
    """
    arity = _flag_table()['arity']
    family = _driver_family(driver)

    def group(name: str) -> set:
        g = arity[name]
        out = set(g.get('all', ()))
        out |= set(g.get(family, ()))
        return out

    path = arity['path_pair']
    return {
        'drop': set(arity['drop'].get('all', ())),
        'keep_single': set(arity['keep_single'].get('all', ())),
        'structural': set(arity['structural_pair'].get('all', ())),
        'semantic': set(arity['semantic_pair'].get('all', ())),
        'path': set(path['by_driver'].get(family, path.get('all', ()))),
        'link_only': tuple(arity['link_only'].get('all', ())),
        'module_dir': tuple(arity['module_dir']['by_driver'].get(family, ())),
    }


def flags_from_command(command: str, source: str) -> list[str]:
    """The flags of a unit's own command, with the structural parts removed.

    Recovered rather than stored separately: the command IS the authority,
    so re-deriving keeps one instead of two that can disagree.

    ``-c``, ``-o``, ``-I``, ``-J``, ``-MT``/``-MF``/``-MQ`` and their
    operands go STRUCTURALLY — removing a flag but keeping its operand
    leaves a bare path among the compile options, and the compiler then
    reads it as another input file.

    ``-fpreprocessed`` goes for a different reason: it is a fact about the
    INTERMEDIATE this build handed the compiler, not about the unit.  CMake
    compiles a scanned Fortran source in two steps and marks the second one
    with it; a replay compiles the corpus's own source, where the flag tells
    the compiler to skip directives that are still there.
    """
    try:
        argv = shlex.split(command)
    except ValueError as exc:
        raise ProtocolError(f'unparsable command: {exc}') from exc

    src_abs = str(Path(source))
    src_name = Path(source).name
    # The grammar is a lookup, not a set of literals: which spellings take an
    # operand (and which of those name a path we must keep) depends on the
    # DRIVER, and the recorded command names it.
    g = _flags_of(argv[0] if argv else '')
    takes_operand = g['structural'] | g['semantic'] | g['path']
    out: list[str] = []
    i = 1                     # argv[0] is the driver
    while i < len(argv):
        tok = argv[i]
        # Arity is the thing to get right: a flag that takes an OPERAND and
        # is counted as taking none leaves the operand behind as a bare
        # token, and the compiler reads it as another input file.  A flag
        # with NO operand that is counted as taking one swallows whatever
        # follows it.
        if tok in g['drop']:
            i += 1
            continue
        if tok in g['keep_single'] and tok not in takes_operand:
            out.append(tok)             # no operand, but it MEANS something
            i += 1
            continue
        if tok in g['structural']:
            i += 2                      # the flag AND its operand, dropped
            continue
        if tok in g['semantic'] and i + 1 < len(argv):
            out += [tok, argv[i + 1]]
            i += 2
            continue
        if tok in g['path']:
            if tok in g['module_dir']:
                i += 2              # the module directory is the build's
                continue
            if i + 1 < len(argv):
                out += [tok, argv[i + 1]]
                i += 2
                continue
        if len(tok) > 2 and (tok[:2] in (g['path'] | g['semantic'])
                             or any(tok.startswith(m)
                                    for m in g['module_dir'])):
            if any(tok.startswith(m) for m in g['module_dir']):
                i += 1              # the module directory is the build's
                continue
            out.append(tok)             # the attached spelling
            i += 1
            continue
        # The source itself, in any of the three ways a build names it: the
        # entry's own spelling, its basename, and the PREPROCESS INTERMEDIATE
        # this build compiled INSTEAD of it.  That third one is the one a
        # string compare against the source cannot catch, and it is a file
        # no other build has.
        #
        # The intermediate's EXTENSION is lowercased (CMake turns
        # `la_xisnan.F90` into `la_xisnan-pp.f90`), so the match is on the
        # stem and case-insensitive.  A case-sensitive `-pp.F90` comparison
        # missed it, the path stayed in the flag list, and it reached the
        # compiler as a COMPILE_OPTION — a second input file.  Measured:
        # `gfortran: fatal error: cannot specify '-o' with '-c', '-S' or '-E'
        # with multiple files`, and the whole corpus failed to replay.
        pname = Path(tok).name
        if (tok == src_abs or tok == src_name or src_name in pname
                or pname.lower().startswith(
                    Path(src_name).stem.lower() + '-pp')):
            i += 1
            continue
        out.append(tok)
        i += 1
    return out
