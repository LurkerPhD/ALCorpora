"""One flat CMake build that replays a protocol.

The protocol says what the build is — its units, its link products, its
generated inputs.  This emits ONE ``CMakeLists.txt`` that builds exactly
that, as-is.  There is no conversion and no state: the units are compiled in
the language the protocol records for them, in the order CMake derives from
their own module/header dependencies, and the products link from them.

**Intent, not commands.**  The protocol carries a full command per unit, so
this could emit one ``add_custom_command`` each and reproduce every command
character for character.  It deliberately does not.  Expressing the intent
— these sources, these flags, this product — and letting CMake assemble the
command keeps what CMake already does correctly:

* module and header dependencies, including the ``.mod`` ordering a Fortran
  build needs, which a dispatched build would have to reimplement;
* output naming and directories, which a per-unit command would pin to the
  spelling the protocol was captured with.

The cost is that a command is REASSEMBLED rather than copied, so it can
drift — which is what the protocol's own record of the command is for.
"""

from __future__ import annotations

import json
import os
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

from protocolize.private_protocol import (CompileEntry, Protocol, ProtocolError,
                                  expand_tree)

_HEADER = """\
# Generated by protocolize — a flat build that replays a protocol.
# Do not edit: regenerate from the protocol.
cmake_minimum_required(VERSION 3.16)
"""


@dataclass
class Selection:
    """The units this build compiles.

    A LIST, not a stem-keyed map: one stem may be two units — a Fortran
    module and the C it binds — so the stem is the unit's IDENTITY but not a
    unique key.
    """

    entries: list[CompileEntry] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)


def select(protocol: Protocol) -> Selection:
    """The protocol's units, as a list.

    A unit is identified by its stem, but a stem may be TWO units — a Fortran
    module and the C it binds — so this is a list, and a product's members
    (stems) resolve to every unit of that stem.
    """
    return Selection(entries=list(protocol.compilation))


def object_name_for(stem: str, language: str) -> str:
    """The object name CMake gives a source, for a product's member list."""
    del language
    return f'{stem}.o'



def flat_cmake(protocol: Protocol, *, tree: str | Path,
               extra_includes: Sequence[str] = (),
               extra_links: Sequence[str] = (),
               name: str = 'CMakeLists.txt') -> str:
    """Write the flat CMakeLists that replays *protocol*; return its path.

    **Self-contained on purpose.**  This module knows nothing about any
    project: it takes a protocol and produces a build.

    *extra_includes* and *extra_links* are the CALLER's declarations — an
    include directory a converted source needs, a library to put on a
    product's link line.  They are empty by default: a pure replay of a
    protocol needs neither, and anything a specific toolchain wants is the
    caller's to add.  A path guessed here would be right by coincidence and
    wrong in a way that surfaces as a missing header deep in a build.
    """
    tree_s = str(tree)
    text = _render(protocol, select(protocol), tree_s,
                   list(extra_includes), list(extra_links))
    out = Path(tree) / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    # The response files, written where the commands that read them expect.
    # Every input on its own line, which is the format a generator uses and
    # the reason it exists: a command line too long to spell out.
    by_stem: dict[str, list] = {}
    for e in protocol.compilation:
        by_stem.setdefault(e.stem, []).append(e)
    for prod in protocol.products:
        cwd = _expand(prod.directory, tree) if prod.directory else tree
        for rsp in prod.rspfiles:
            rsp_path = Path(_expand(rsp, tree))
            if not str(rsp_path).startswith(os.sep):
                # Relative to the DIRECTORY THE COMMAND RUNS IN, exactly as
                # the `@<path>` operand in it is.
                rsp_path = Path(cwd) / rsp_path
            rsp_path.parent.mkdir(parents=True, exist_ok=True)
            entries = [_unit_output(o, tree)
                       for stem in prod.stems for o in by_stem.get(stem, ())]
            rsp_path.write_text('\n'.join(entries) + '\n', encoding='utf-8')
    return str(out)


def _render(protocol: Protocol, selection: Selection, tree: str,
            extra_includes: list[str], extra_links: list[str]) -> str:
    lines: list[str] = [_HEADER, '']
    has_fortran = _has_fortran(selection)
    if not has_fortran:
        lines.append('project(replay LANGUAGES C CXX)')
    else:
        lines.append('project(replay LANGUAGES C CXX Fortran)')
    # NO global CMAKE_POSITION_INDEPENDENT_CODE.  Forcing PIC on every unit
    # adds a flag the protocol's own commands do not carry, and it is not
    # cosmetic: measured on a project that compiles with
    # `-fvisibility=hidden`, the added PIC made the linker LOCALISE `main`
    # (`T` -> `t`) in every test executable, so 19 products "differed" while
    # their code was identical.  CMake already applies PIC where it belongs —
    # a SHARED library — so a replay that adds nothing matches the build.
    if has_fortran:
        # The MODULE DIRECTORY is the build system's to manage, and it has to
        # be, because a `.mod` is a compile-time dependency and nothing in a
        # flat list of sources says so.  CMake scans a Fortran source for its
        # `use` statements, writes every module into this one directory, and
        # derives the compile ORDER from that — which is the whole reason the
        # flags a unit was compiled with are not replayed verbatim (see the
        # flag table's `module_dir`).
        #
        # BEFORE the first target, because that is when CMake READS it: the
        # variable is consulted as each target is created, so a `set()`
        # emitted after them is dead code that looks like a declaration.
        # Measured: set at line 16850 with the first target at 13479, so all
        # 1306 `.mod` files landed in the build root instead of here — and
        # the build still succeeded, which is why nobody noticed.
        lines.append(
            f'set(CMAKE_Fortran_MODULE_DIRECTORY "{tree}/bin/mod")')
        if not _build_preprocesses(selection):
            # The SCAN is a C preprocessor, and it is not free.  CMake runs
            # one over every Fortran source to find its `use` statements, so
            # a fixed-form source whose COMMENT contains `/*` dies:
            #
            #   C   ... REPLACEING !* BY /* IN RDMAP ARRAY
            #   Error: unterminated comment
            #
            # Measured on NASTRAN-95, whose build compiles all 1830 units in
            # ONE step (`gfortran -c -o x.o x.f`, no `-cpp`): the added scan
            # turned a valid corpus into a build that fails on a comment.
            # A replay declares what the corpus does, no more.
            #
            # OFF and not "unset": unset is the default, and the default is
            # ON.  Before the first target, for the same reason the module
            # directory is — CMake reads it as each target is created.
            lines.append('set(CMAKE_Fortran_PREPROCESS OFF)')
    lines.append('')

    # ── the sources the build must MAKE first ──
    # A corpus that generates sources compiles files it does not ship --
    # LAPACK's 3,489 `_64` mirrors, MYSTRAN's 570.  Each is recorded with
    # the command that produces it; emitting that command back is what makes
    # a replay possible at all, and leaving it out is a build that dies on
    # one missing file among thousands.
    generated = _generated_rules(protocol, tree)
    if generated:
        lines.append('# Sources this build must generate before compiling.')
        for out, command, depends in generated:
            lines.append(f'add_custom_command(OUTPUT "{_cmake_string(out)}"')
            # Every rule runs in a shell, because the recorded command IS a
            # shell line: a build system runs its commands through one, and
            # the recorded text contains `cd X && ...` and its own quoting.
            # Handing it to CMake as an argument list would split it wrongly.
            # The parent directory is made first: in a FRESH tree the
            # directory a generated source lands in does not exist, and the
            # generator is not obliged to create it.
            parent = str(Path(out).parent)
            lines.append(f'  COMMAND "${{CMAKE_COMMAND}}" -E make_directory '
                         f'"{_cmake_string(parent)}"')
            lines.append(_command_line(command))
            for dep in depends:
                lines.append(f'  DEPENDS "{_cmake_string(dep)}"')
            lines.append('  VERBATIM)')
        lines.append('')

    # ── the units ──
    # Each unit is replayed by running the EXACT command the build recorded,
    # in the directory it ran in, with `${TREE}` re-pointed at THIS tree.  The
    # command is the authority on flags, source spelling and output path.
    # Re-deriving a compile from the flags drifts: measured on a real project
    # (compiled with -fvisibility=hidden), expressing "these flags" and
    # letting CMake reassemble the command produced -rdynamic on the link
    # lines and a LOCALISED `main` in the executables that the project's own
    # build did not have -- 19 products "differed" while their code was
    # identical.
    #
    # The ORDER among units is still ours: a custom command has no dependency
    # of its own, so a unit DEPENDS on the object of every module it uses.
    provider: dict[str, str] = {}
    for e in selection.entries:
        for mod in e.provides:
            provider.setdefault(mod.casefold(), e.stem)
    by_stem: dict[str, list[CompileEntry]] = {}
    for e in selection.entries:
        by_stem.setdefault(e.stem, []).append(e)
    for e in sorted(selection.entries, key=lambda x: (x.stem, x.language)):
        stem = e.stem
        cwd = _expand(e.directory, tree)
        out = _unit_output(e, tree)
        deps = [_expand(e.file, tree)]
        for mod in e.uses:
            owner = provider.get(mod.casefold())
            if owner is not None and owner != stem and owner in by_stem:
                deps += [_unit_output(o, tree) for o in by_stem[owner]]
        lines.append(f'# {stem} ({e.language or "?"})')
        # A unit the build compiles in TWO steps (a scanned source: preprocess
        # then compile) is replayed in two: the preprocess command makes the
        # intermediate, and the compile command consumes it.  Replaying only
        # the compile command names an intermediate nothing created, and
        # replaying it against the SOURCE would drop the defines that live on
        # the preprocess edge alone.
        if e.preprocess:
            pp = _output_operand(e.preprocess, cwd, tree) or out
            lines.append(f'add_custom_command(OUTPUT "{_cmake_string(pp)}"')
            lines.append('  WORKING_DIRECTORY '
                         f'"{_cmake_string(cwd)}"')
            lines.append('  COMMAND "${CMAKE_COMMAND}" -E make_directory '
                         f'"{_cmake_string(str(Path(pp).parent))}"')
            lines.append(_command_line(_expand(e.preprocess, tree)))
            lines.append(f'  DEPENDS "{_cmake_string(_expand(e.file, tree))}"')
            lines.append('  VERBATIM)')
            deps = [pp] + deps
        lines.append(f'add_custom_command(OUTPUT "{_cmake_string(out)}"')
        lines.append('  WORKING_DIRECTORY '
                     f'"{_cmake_string(cwd)}"')
        lines.append('  COMMAND "${CMAKE_COMMAND}" -E make_directory '
                     f'"{_cmake_string(str(Path(out).parent))}"')
        lines.append(_command_line(_expand(e.command_line(), tree)))
        for dep in dict.fromkeys(deps):
            lines.append(f'  DEPENDS "{_cmake_string(dep)}"')
        lines.append('  VERBATIM)')
    lines.append('')

    # ── the products ──
    # The EXACT link/archive command the build recorded, in the directory it
    # ran in.  Nothing about the link line is re-derived (see the units'
    # note); a product DEPENDS on its members' objects and on the products of
    # the libraries it links.
    by_output = {_expand(p.output, tree): p for p in protocol.products}
    for i, prod in enumerate(protocol.products):
        out = _expand(prod.output, tree)
        cwd = _expand(prod.directory, tree) if prod.directory else tree
        deps: list[str] = []
        for stem in prod.stems:
            deps += [_unit_output(o, tree) for o in by_stem.get(stem, ())]
        for lib in prod.libs:
            ref = _expand(lib, tree)
            if ref in by_output:
                deps.append(_expand(by_output[ref].output, tree))
        lines.append(f'add_custom_command(OUTPUT "{_cmake_string(out)}"')
        lines.append('  WORKING_DIRECTORY '
                     f'"{_cmake_string(cwd)}"')
        lines.append('  COMMAND "${CMAKE_COMMAND}" -E make_directory '
                     f'"{_cmake_string(str(Path(out).parent))}"')
        if prod.command:
            # A response file the command reads is THIS build's to make: the
            # generator that owned it declared it nowhere, so a replay that
            # does not write it archives against a path that exists in neither
            # tree.  Its CONTENT is the product's inputs, one per line — which
            # is what a generator puts there, and what the protocol already
            # carries as `stems`.  Nothing is re-derived from the command.
            for rsp in prod.rspfiles:
                rsp_path = _expand(rsp, tree)
                if not str(rsp_path).startswith(os.sep):
                    rsp_path = str(Path(cwd) / rsp_path)
                lines.append('  COMMAND "${CMAKE_COMMAND}" -E make_directory '
                             f'"{_cmake_string(str(Path(rsp_path).parent))}"')
            lines.append(_command_line(_expand(prod.command, tree)))
        for dep in dict.fromkeys(deps):
            lines.append(f'  DEPENDS "{_cmake_string(dep)}"')
        lines.append('  VERBATIM)')
    lines.append('')
    if protocol.products:
        outputs = ' '.join(f'"{_cmake_string(_expand(p.output, tree))}"'
                           for p in protocol.products)
        lines.append(f'add_custom_target(_replay ALL DEPENDS {outputs})')
    lines.append('')

    # ── the caller's extra include directories ──
    # Empty by default: a pure replay needs none, and a path this generator
    # invented would be right by coincidence and wrong where it matters.
    for inc in extra_includes:
        lines.append(f'include_directories("{_cmake_string(inc)}")')

    # ── the corpus's own TEST registrations ──
    # A build that can be generated must also be RUNNABLE the way the project
    # runs it, and for a self-verifying corpus the suite IS the verdict: its
    # drivers check their own residuals and the aggregate table decides.  A
    # generated build with no registrations therefore cannot be verified at
    # all — measured, the tree built 7045/7045 objects and the benchmark died
    # in 0.022s with "no CTest registration".
    #
    # Nothing here is invented: the entries are the protocol's, captured
    # through the build system's own `ctest --show-only=json-v1`, re-spelled
    # against THIS tree so a replay registers its own artifacts rather than
    # the ones the protocol was captured from.
    # Files the tests READ that the build neither compiles nor generates.
    # Written as text, because there is no command to replay: LAPACK's
    # `*_64.in` are derived by a `string(REPLACE)` in the project's own
    # CMakeLists, and `lapack_testing.py` is `file(COPY)`d in.  CMake writes
    # them the same way, at configure time.
    support = list(getattr(protocol, 'support_files', ()) or ())
    for f in support:
        rel = _cmake_string(str(f.get('path') or ''))
        content = f.get('content')
        if not rel or content is None:
            continue
        # Written where CMake's own `file(COPY)` would have put it: the
        # BINARY directory.  The tests reference these by paths spelled
        # `CMAKE_CURRENT_BINARY_DIR` (see the re-rooting above), so writing
        # them to the source tree puts them one level away from every reader
        # — and the failure is a test that cannot find its input file.
        out_path = '${CMAKE_CURRENT_BINARY_DIR}/' + rel.replace('\\', '/')
        # A CMake BRACKET argument, because the content is source code: quotes,
        # semicolons and backslashes all survive it with no escaping at all.
        # The delimiter carries as many `=` as it takes for its own closing
        # sequence to be absent from the content — a fixed `[[...]]` breaks on
        # any file containing `]]`, and the failure is a PARSE error naming
        # the bracket rather than the file.
        eq = ''
        while f']{eq}]' in content:
            eq += '='
        # `file(WRITE)` does not create directories, and a registration
        # whose working directory does not exist is "Failed to change
        # working directory" rather than a missing file — the error names
        # the directory and not what would have been in it.
        parent = str(Path(out_path.replace('${CMAKE_CURRENT_BINARY_DIR}',
                                           '.'))).replace('\\', '/')
        parent = parent.rsplit('/', 1)[0]
        if parent and parent != '.':
            lines.append('')
            lines.append(f'file(MAKE_DIRECTORY '
                         f'"${{CMAKE_CURRENT_BINARY_DIR}}/{parent[2:]}")')
        lines.append('')
        lines.append(f'file(WRITE "{_cmake_string(out_path)}" '
                     f'[{eq}[{content}]{eq}])')

    tests = list(getattr(protocol, 'tests', ()) or ())
    if tests:
        lines.append('')
        lines.append('# The corpus\'s own test registrations, from the protocol.')
        lines.append('enable_testing()')
        # A registration's paths were resolved against the CAPTURE tree, so
        # they are spelled `${TREE}/...` when under it, or absolute when
        # outside.  A replay puts each product at the SAME `${TREE}`-relative
        # place its recorded command wrote it — the build is a verbatim replay —
        # so expanding `${TREE}` to THIS tree is all that is needed.  (An
        # earlier generator picked its own output directory and had to re-root
        # every path to it; a verbatim replay has no such choice to make.)
        tree_norm = str(tree).replace(chr(92), '/').rstrip('/')

        def _test_path(text: str) -> str:
            # The tree placeholder can sit INSIDE an argument rather than at
            # its start: `-DOUTPUT=${TREE}/TESTING/dec.out`.  `expand_tree`
            # handles that, and refuses a bare `$` rather than passing it on.
            return expand_tree(_cmake_string(str(text)), tree)

        def _under_tree(path: str) -> bool:
            return path == tree_norm or path.startswith(tree_norm + '/')

        # A registration whose WORKING_DIRECTORY does not exist fails with
        # "Failed to change working directory" — which names the directory
        # and not the test, so it is worth creating them all up front.  The
        # project's own CMakeLists gets them as a side effect of building
        # there; a generated build has to say so.
        # Every directory a test WRITES into, as well as the one it runs in.
        # The suite's aggregator (`lapack_testing.py`) discovers its inputs by
        # walking `<TESTING>/EIG`, `/LIN`, `/MATGEN`, so a directory that the
        # drivers would have created by writing into it has to exist before
        # the aggregator looks — otherwise it reports "testing directory
        # TESTING not found" and the whole run reads as a failure while 214 of
        # 215 tests passed.
        out_dirs: set[str] = set()
        for t in tests:
            for arg in (t.get('command') or ()):
                head, sep, value = _test_path(str(arg)).partition('=')
                if sep and head.startswith('-DOUTPUT') and value:
                    out_dirs.add(str(Path(value).parent))
        wd_dirs = {
            _test_path(str(t.get('working_directory')))
            for t in tests if t.get('working_directory')} | out_dirs
        for wd in sorted(wd_dirs):
            if _under_tree(wd.replace('\\', '/')):
                lines.append(f'file(MAKE_DIRECTORY "{_cmake_string(wd)}")')
        seen_names: set[str] = set()
        for t in tests:
            name = _cmake_string(str(t.get('name') or ''))
            command = [_test_path(c) for c in (t.get('command') or ())]
            if not name or not command:
                continue
            if name in seen_names:
                # `add_test` REFUSES a duplicate NAME.  A project can register
                # one, and the capture can see a name twice; the FIRST is
                # registered and the repeat skipped, because two tests of one
                # name cannot coexist in a build.
                continue
            seen_names.add(name)
            lines.append(f'add_test(NAME "{name}" COMMAND '
                         + ' '.join(f'"{c}"' for c in command) + ')')
            props: list[str] = []
            wd = t.get('working_directory')
            if wd:
                props.append(
                    f'WORKING_DIRECTORY "{_test_path(wd)}"')
            deps = t.get('depends') or []
            if deps:
                joined = ';'.join(str(d) for d in deps)
                props.append(f'DEPENDS "{joined}"')
            if props:
                lines.append(f'set_tests_properties("{name}" PROPERTIES '
                             + ' '.join(props) + ')')
    return '\n'.join(lines) + '\n'


def _resolve(path: str, tree: str) -> str:
    """*path* as an absolute path, relative spellings taken against *tree*."""
    p = Path(path)
    return str(p if p.is_absolute() else Path(tree) / p)


def _build_preprocesses(selection: Selection) -> bool:
    """Did the corpus's own build preprocess its Fortran sources?

    Asked of the entries, which RECORD it: a unit that went through a
    preprocess edge carries one, and a build with no such edge did not
    preprocess. The distinction is load-bearing in both directions — a
    corpus that preprocessed needs the scan (its `-D` set lives on that edge,
    and a converted unit has no Fortran scan in front of it), and one that did
    not must not acquire one.
    """
    return any(e.preprocess for e in selection.entries)


def _has_fortran(selection: Selection) -> bool:
    return any((e.language or 'fortran') == 'fortran'
               for e in selection.entries)


def _ident(stem: str) -> str:
    return ''.join(c if c.isalnum() else '_' for c in stem)


def _output_operand(command: str, cwd: str, tree: str) -> str | None:
    """The path a command's ``-o`` names, absolute, or ``None``.

    Used to locate the intermediate a preprocess step writes, so the compile
    step that consumes it can depend on it.  Relative to *cwd*, the directory
    the command runs in — the same convention a compile database uses.
    """
    try:
        argv = shlex.split(_expand(command, tree))
    except ValueError:
        return None
    if '-o' not in argv:
        return None
    i = argv.index('-o')
    if i + 1 >= len(argv):
        return None
    p = Path(argv[i + 1])
    return str(p if p.is_absolute() else Path(cwd) / p)


def _unit_output(e: CompileEntry, tree: str) -> str:
    """The object the unit's own command writes, as an absolute path.

    Read off the entry, not invented: the command's ``-o`` operand is
    relative to the unit's ``directory`` (the same convention
    compile_commands.json uses), so the path is ``directory/output``.  The
    command is replayed verbatim in that directory, so this is exactly where
    the object lands — no rewriting, and the link line's own relative
    reference to it resolves the same way.
    """
    cwd = Path(_expand(e.directory, tree))
    out = Path(_expand(e.output, tree))
    return str(out if out.is_absolute() else cwd / out)


def _expand(text: str, tree: str) -> str:
    """Expand the placeholder, refusing a result CMake would misread.

    ``${TREE}`` left in the text is NOT harmless: CMake spells its own
    variables ``${...}``, so a leftover placeholder is read as an empty
    CMake variable and every path silently loses its root.
    """
    out = expand_tree(text, tree)
    if '${' in out:
        raise ProtocolError(
            f'{text!r} still holds a "${{...}}" after expansion, which CMake '
            f'reads as one of its own (empty) variables')
    return out


def _cmake_string(text: str) -> str:
    return text.replace('\\', '/')


def _generated_rules(protocol: Protocol, tree: str) -> list[tuple]:
    """``(output, command, depends)`` for each generated source, expanded.

    Deduped by output: a build system may declare one generated file twice
    (once relative to the tree, once absolutely), and two rules producing
    one file is a build that either races or refuses.
    """
    seen: dict[str, tuple] = {}
    for g in protocol.generated_inputs:
        out = _expand(g['output'], tree)
        if out in seen:
            continue
        depends = [_expand(d, tree) for d in (g.get('depends') or ())]
        seen[out] = (out, _expand(g['command'], tree), depends)
    return [seen[k] for k in sorted(seen)]


def _shell_arg(command: str) -> str:
    r"""*command* escaped to sit inside a CMake double-quoted argument.

    Only a backslash and a double quote need escaping for CMake's own
    else -- including the quotes the recorded command carries around its own
    arguments -- must reach the shell as written, because it is the shell
    that has to read them.
    """
    return command.replace('\\', '\\\\').replace('"', '\\"')


#: A single execve ARGUMENT may not exceed Linux's ``MAX_ARG_STRLEN``
#: (131072), and the limit is PER ARGUMENT — not on the total.  Measured:
#: ``sh -c`` with a 65,536-byte argument runs; at 131,071 execve itself fails
#: with E2BIG, before the shell starts.
#:
#: This matters because a link line grows with the unit count.  Measured on a
#: real corpus: its 1,965-object link is 126,616 bytes and its own build
#: system runs it through ``sh -c`` — four thousand bytes under the wall, and
#: only because that build spells its objects RELATIVELY.  Spell the same
#: objects under ``${TREE}`` and the line grows by ~20KB and dies.
#:
#: The fix is NOT to shorten anything, and not to hand the shell a file: it is
#: to stop PACKING the command into one argument.  A command passed as
#: separate argv entries is limited only by the total (about 2MB here), which
#: is what the native build does and why it survives.  Measured: a 253KB
#: command delivered as separate arguments runs; the same command as one
#: ``sh -c`` string fails with E2BIG.
_SHELL_OPERATORS = frozenset({'&&', '||', ';', '|', '&', '>', '>>', '<',
                              '2>', '2>>', '<<', '<<<'})


def _command_argv(command: str) -> list[str] | None:
    """*command* as argv, or ``None`` when it genuinely needs a shell.

    A command with shell OPERATORS (`a && b`, a redirect) must go through a
    shell, and is emitted as ``sh -c`` — those commands are short (a
    generated source, a chained generator), so the one-argument limit is not
    in play.

    A plain command has no operators and no need for a shell, and emitting it
    as separate arguments is strictly better: the shell would have done
    nothing but exec it.

    The one shell-idiosyncratic token stripped here is a LEADING or TRAILING
    ``:`` (the shell's own no-op, which build systems wrap a command in to
    keep its exit status — `: && X && :` means exactly `X`).  A ``:`` in the
    middle is left alone, because there it would be a real command.
    """
    try:
        toks = shlex.split(command)
    except ValueError:
        return None
    if not toks:
        return None
    while toks and toks[0] in (':', '&&', '||'):
        toks = toks[1:]
    while toks and toks[-1] in (':', '&&', '||'):
        toks = toks[:-1]
    if not toks:
        return None
    if any(t in _SHELL_OPERATORS for t in toks):
        return None                  # a real shell line: keep the shell
    return toks


def _command_line(command: str) -> str:
    """The CMake ``COMMAND`` line(s) that run *command*.

    One command, delivered the way that keeps it runnable at any size: as
    separate arguments when it is a plain command, through a shell when it
    carries shell syntax.  Nothing about the command is re-derived.
    """
    argv = _command_argv(command)
    if argv is None:
        return f'  COMMAND sh -c "{_shell_arg(command)}"'
    return '  COMMAND ' + ' '.join(f'"{_cmake_string(a)}"' for a in argv)
def _cmake_list(items: 'Iterable[str]') -> str:
    """*items* as one CMake list value.

    ``;`` separates a list, and the flags themselves are passed through
    ESCAPED rather than re-quoted: a definition like
    ``-DF2C_ABI_GFORTRAN=""`` already carries quotes the compiler must see,
    and wrapping it again hands over different text than the build recorded.
    """
    out = []
    for item in items:
        out.append(_cmake_string(item)
                   .replace('\\', '\\\\').replace(';', '\\;')
                   .replace('"', '\\"'))
    return ';'.join(out)


#: The compiler option grammar, as data.  See the file's own `comment`.
#:
#: A driver's option grammar is fixed and documented, so it is enumerable —
#: and enumerable is exactly why it belongs in a table rather than in an
#: if-chain.  Hard-coded here, it would be one compiler's grammar wearing a
#: general name, and every other compiler would be silently mis-parsed:
#: arity is the thing that must be right, and getting it wrong is quiet (a
#: flag that takes an operand and is counted as taking none leaves the
#: operand behind as another input file).
_FLAG_TABLE: dict | None = None


def _flag_table() -> dict:
    """The driver option grammar, loaded once."""
    global _FLAG_TABLE
    if _FLAG_TABLE is None:
        path = Path(__file__).resolve().parent / 'data' / 'compiler_flags.json'
        _FLAG_TABLE = json.loads(path.read_text(encoding='utf-8'))
    return _FLAG_TABLE


def _driver_family(driver: str) -> str:
    """Which option grammar *driver* speaks, by its own basename."""
    name = Path(driver).name
    for family, prefixes in _flag_table()['drivers'].items():
        if family == 'comment':
            continue
        if any(name.startswith(p) for p in prefixes):
            return family
    return 'gfortran'          # the driver this project is built around


def _flags_of(driver: str) -> dict:
    """The four sets :func:`flags_from_command` classifies with.

    Copied out of the table and closed over the driver, so the loop below
    asks set membership rather than re-deriving the family per token.
    """
    arity = _flag_table()['arity']
    family = _driver_family(driver)

    def group(name: str) -> set:
        g = arity[name]
        out = set(g.get('all', ()))
        out |= set(g.get(family, ()))
        return out

    path = arity['path_pair']
    return {
        'drop': set(arity['drop'].get('all', ())),
        'keep_single': set(arity['keep_single'].get('all', ())),
        'structural': set(arity['structural_pair'].get('all', ())),
        'semantic': set(arity['semantic_pair'].get('all', ())),
        'path': set(path['by_driver'].get(family, path.get('all', ()))),
        'link_only': tuple(arity['link_only'].get('all', ())),
        'module_dir': tuple(arity['module_dir']['by_driver'].get(family, ())),
    }


def flags_from_command(command: str, source: str) -> list[str]:
    """The flags of a unit's own command, with the structural parts removed.

    Recovered rather than stored separately: the command IS the authority,
    so re-deriving keeps one instead of two that can disagree.

    ``-c``, ``-o``, ``-I``, ``-J``, ``-MT``/``-MF``/``-MQ`` and their
    operands go STRUCTURALLY — removing a flag but keeping its operand
    leaves a bare path among the compile options, and the compiler then
    reads it as another input file.

    ``-fpreprocessed`` goes for a different reason: it is a fact about the
    INTERMEDIATE this build handed the compiler, not about the unit.  CMake
    compiles a scanned Fortran source in two steps and marks the second one
    with it; a replay compiles the corpus's own source, where the flag tells
    the compiler to skip directives that are still there.
    """
    try:
        argv = shlex.split(command)
    except ValueError as exc:
        raise ProtocolError(f'unparsable command: {exc}') from exc

    src_abs = str(Path(source))
    src_name = Path(source).name
    # The grammar is a lookup, not a set of literals: which spellings take an
    # operand (and which of those name a path we must keep) depends on the
    # DRIVER, and the recorded command names it.
    g = _flags_of(argv[0] if argv else '')
    takes_operand = g['structural'] | g['semantic'] | g['path']
    out: list[str] = []
    i = 1                     # argv[0] is the driver
    while i < len(argv):
        tok = argv[i]
        # Arity is the thing to get right: a flag that takes an OPERAND and
        # is counted as taking none leaves the operand behind as a bare
        # token, and the compiler reads it as another input file.  A flag
        # with NO operand that is counted as taking one swallows whatever
        # follows it.
        if tok in g['drop']:
            i += 1
            continue
        if tok in g['keep_single'] and tok not in takes_operand:
            out.append(tok)             # no operand, but it MEANS something
            i += 1
            continue
        if tok in g['structural']:
            i += 2                      # the flag AND its operand, dropped
            continue
        if tok in g['semantic'] and i + 1 < len(argv):
            out += [tok, argv[i + 1]]
            i += 2
            continue
        if tok in g['path']:
            if tok in g['module_dir']:
                i += 2              # the module directory is the build's
                continue
            if i + 1 < len(argv):
                out += [tok, argv[i + 1]]
                i += 2
                continue
        if len(tok) > 2 and (tok[:2] in (g['path'] | g['semantic'])
                             or any(tok.startswith(m)
                                    for m in g['module_dir'])):
            if any(tok.startswith(m) for m in g['module_dir']):
                i += 1              # the module directory is the build's
                continue
            out.append(tok)             # the attached spelling
            i += 1
            continue
        # The source itself, in any of the three ways a build names it: the
        # entry's own spelling, its basename, and the PREPROCESS INTERMEDIATE
        # this build compiled INSTEAD of it.  That third one is the one a
        # string compare against the source cannot catch, and it is a file
        # no other build has.
        #
        # The intermediate's EXTENSION is lowercased (CMake turns
        # `la_xisnan.F90` into `la_xisnan-pp.f90`), so the match is on the
        # stem and case-insensitive.  A case-sensitive `-pp.F90` comparison
        # missed it, the path stayed in the flag list, and it reached the
        # compiler as a COMPILE_OPTION — a second input file.  Measured:
        # `gfortran: fatal error: cannot specify '-o' with '-c', '-S' or '-E'
        # with multiple files`, and the whole corpus failed to replay.
        pname = Path(tok).name
        if (tok == src_abs or tok == src_name or src_name in pname
                or pname.lower().startswith(
                    Path(src_name).stem.lower() + '-pp')):
            i += 1
            continue
        out.append(tok)
        i += 1
    return out
